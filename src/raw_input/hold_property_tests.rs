/// A case of typed reads after a released Escape, through the Unix reader.
fn escape_then_typed(reads: &[(u64, &[u8])]) -> Case {
    let mut input = vec![ESC];
    let mut case_reads = vec![Read {
        gap: 0,
        bytes: vec![ESC],
        color_queries: 0,
        wait_for_flush: false,
        semantic: false,
        nested: None,
    }];
    for (index, (gap, bytes)) in reads.iter().enumerate() {
        input.extend_from_slice(bytes);
        case_reads.push(Read {
            gap: *gap,
            bytes: bytes.to_vec(),
            color_queries: 0,
            wait_for_flush: index == 0,
            semantic: false,
            nested: None,
        });
    }
    let mut kinds = vec![Kind::Ambiguous];
    kinds.extend(std::iter::repeat_n(Kind::Text, input.len() - 1));
    let mut case = Case {
        config: Config {
            driver: Driver::UnixReader,
            mouse_capture: false,
            color_query: false,
            default_color_query: false,
            disambiguation: false,
            graphics_wait: None,
        },
        reads: case_reads,
        expected: per_byte(&input, Rule::Keep),
        paste_end: vec![None; input.len()],
        kinds,
        token_starts: vec![0, 1],
        input,
    };
    mark_released_prefix_tails(&mut case);
    case
}

/// codex f5251-r4 finding 4 (ADR-0013 D6): typing ambiguity is judged on
/// arrival times. Escape released at 10 ms, `[` typed at 200 ms and `D` at
/// 280 ms: 80 ms apart, not one burst, so both must reach the pane, and an
/// implementation that drops them fails. As one read, they may be dropped.
#[test]
fn oracle_released_prefix_tail_is_judged_on_arrival_times() {
    let case = escape_then_typed(&[(200, b"["), (80, b"D")]);
    assert!(case.expected[1..]
        .iter()
        .all(|unit| matches!(unit.rule, Rule::Deferred { .. })));
    let mut harness = Harness::new(&case, 0);
    harness.run_unix_reader().unwrap();
    let expected = harness.resolve();
    assert_eq!(expected[1].rule, Rule::Keep);
    assert_eq!(expected[2].rule, Rule::Keep);
    assert!(check_output(&expected, &harness.out).is_ok());
    assert!(check_output(&expected, &events(&[b"\x1b"])).is_err());

    let burst = escape_then_typed(&[(200, b"[D")]);
    let mut harness = Harness::new(&burst, 0);
    harness.run_unix_reader().unwrap();
    let expected = harness.resolve();
    assert_eq!(expected[1].rule, Rule::Either);
    assert!(check_output(&expected, &events(&[b"\x1b"])).is_ok());
}

/// codex f5251-r4 finding 4: a report cut by a semantic record is not
/// blanket `Either`. An SGR report whose prefix stayed held through the
/// record may be typed (#4048) but not lost, and the bytes after the record
/// are typed.
#[test]
fn oracle_interrupted_report_is_not_blanket_either() {
    let bytes = b"\x1b[<0;1;1M";
    let cuts = [Cut { at: 4, gap: 20 }];
    let config = Config {
        driver: Driver::WindowsPump,
        mouse_capture: false,
        color_query: false,
        default_color_query: false,
        disambiguation: false,
        graphics_wait: None,
    };
    let units = interrupted_report_rule(Kind::Sgr, bytes, &cuts, 4, &config, 0);
    assert!(units.iter().all(|unit| unit.rule != Rule::Either));
    let mut expected = units[..1].to_vec();
    expected.push(unit(&[SEMANTIC], Rule::KeepEvent));
    expected.extend_from_slice(&units[1..]);
    // Dropped before the record, then the rest typed: allowed.
    let after: Vec<&[u8]> = bytes[4..].iter().map(std::slice::from_ref).collect();
    let mut out = vec![vec![SEMANTIC]];
    out.extend(after.iter().map(|byte| byte.to_vec()));
    assert!(check_output(&expected, &out).is_ok());
    // The bytes after the record lost: rejected.
    assert!(check_output(&expected, &events(&[&[SEMANTIC]])).is_err());
}

/// The classes codex f5251-r5 findings 1 and 2 came from, counted in a
/// case: colour replies cut off before their terminator, X10 frames a
/// control byte or the next ESC ends, nested key records staged behind an
/// X10 frame (a control key, or report payload), and nested records on
/// their own. codex f5251-r7 finding 1: nested records that type no
/// character, staged behind an X10 frame (they have no input bytes, so
/// they are counted from the reads).
#[derive(Debug, Default)]
struct ExtendedCoverage {
    unterminated_colors: usize,
    control_ended_frames: usize,
    escape_ended_frames: usize,
    staged_control_keys: usize,
    staged_report_keys: usize,
    standalone_keys: usize,
    staged_silent_keys: usize,
    /// herdr-vqok: byte-free Ctrl+Space repeats of a Space button record,
    /// and their releases.
    byte_free_repeats: usize,
    byte_free_repeat_releases: usize,
}

impl ExtendedCoverage {
    fn count(&mut self, case: &Case) {
        for record in case.reads.iter().filter_map(|read| read.nested) {
            if record.virtual_key_code == 0x20
                && record.unicode == 0
                && record.control_key_state == LEFT_CTRL_PRESSED
            {
                if record.key_down {
                    self.byte_free_repeats += 1;
                } else {
                    self.byte_free_repeat_releases += 1;
                }
            }
        }
        self.staged_silent_keys += case
            .reads
            .iter()
            .filter(|read| {
                read.nested
                    .is_some_and(|record| record.key_down && record.unicode == 0)
            })
            .count();
        let ends: Vec<usize> = case
            .token_starts
            .iter()
            .skip(1)
            .copied()
            .chain([case.input.len()])
            .collect();
        // Nested keys since the last open X10 frame, while it may still be
        // waiting for payload.
        let mut staging: Option<usize> = None;
        for (start, end) in case.token_starts.iter().copied().zip(ends) {
            let Some(kind) = case.kinds.get(start) else {
                continue;
            };
            let token = &case.input[start..end];
            let mut next = None;
            match kind {
                Kind::Color if !token.ends_with(b"\x07") && !token.ends_with(b"\x1b\\") => {
                    self.unterminated_colors += 1;
                }
                Kind::BrokenX10 if token.last().is_some_and(|byte| *byte < 0x20) => {
                    self.control_ended_frames += 1;
                }
                Kind::BrokenX10 => self.escape_ended_frames += 1,
                Kind::X10 if token.len() < 6 => next = Some(0),
                Kind::Nested => match staging {
                    Some(keys) if keys < 3 && token[0] < 0x20 => self.staged_control_keys += 1,
                    Some(keys) if keys < 3 => {
                        self.staged_report_keys += 1;
                        next = Some(keys + 1);
                    }
                    _ => self.standalone_keys += 1,
                },
                _ => {}
            }
            staging = next;
        }
    }
}

/// codex f5251-r4 findings 3 and 4: the generators reach the paths the
/// harness used to miss, a complete kitty APC introducer, a graphics stream
/// of many small reads (reads that bring the framer nothing), and every
/// generator stream. codex f5251-r5 finding 3: the extended stream reaches
/// the classes behind findings 1 and 2.
#[test]
fn property_generators_cover_graphics_streams_and_both_streams() {
    let mut graphics = 0;
    let mut streams = 0;
    let mut pump_only = 0;
    let mut extended = ExtendedCoverage::default();
    for seed in SEEDS {
        for stream in [Stream::Mixed, Stream::PumpOnly, Stream::Extended] {
            let mut rng = stream.rng(seed);
            for _ in 0..CASES_PER_SEED {
                let case = generate(&mut rng, stream);
                let starts = case
                    .input
                    .windows(GRAPHICS_PREFIX.len())
                    .filter(|window| *window == GRAPHICS_PREFIX)
                    .count();
                graphics += starts;
                streams += usize::from(
                    starts > 0
                        && case
                            .reads
                            .iter()
                            .filter(|read| read.bytes.len() < 25)
                            .count()
                            > 20,
                );
                pump_only += usize::from(
                    stream == Stream::PumpOnly && case.config.driver == Driver::WindowsPump,
                );
                if stream == Stream::Extended {
                    extended.count(&case);
                }
            }
        }
    }
    assert!(graphics > 100, "{graphics} graphics commands");
    assert!(streams > 50, "{streams} graphics streams");
    assert_eq!(pump_only, SEEDS.len() * CASES_PER_SEED);
    let ExtendedCoverage {
        unterminated_colors,
        control_ended_frames,
        escape_ended_frames,
        staged_control_keys,
        staged_report_keys,
        standalone_keys,
        staged_silent_keys,
        byte_free_repeats,
        byte_free_repeat_releases,
    } = extended;
    for count in [
        unterminated_colors,
        control_ended_frames,
        escape_ended_frames,
        staged_control_keys,
        staged_report_keys,
        standalone_keys,
        staged_silent_keys,
    ] {
        assert!(count > 1_000, "{extended:?}");
    }
    for count in [byte_free_repeats, byte_free_repeat_releases] {
        assert!(count > 100, "{extended:?}");
    }
}

/// codex f5251-r5 finding 3 (ADR-0013 D2, D6): the oracle enforces the
/// minimum quiet time before a lossy disposal, not only the maximum age.
/// Windows `ESC [ 3` at 0 ms, a timeout flush right after it, `~` at 1 ms:
/// the prefix is not quiet, so it stays and Delete reaches the pane. A
/// framer without the quiet guard drops `ESC [ 3` at the flush and `~` on
/// arrival, and the oracle must reject that loss, not accept it as
/// `OneOf([Delete], [])`.
#[test]
fn oracle_rejects_loss_before_the_pump_quiet_window() {
    let config = Config {
        driver: Driver::WindowsPump,
        mouse_capture: false,
        color_query: false,
        default_color_query: false,
        disambiguation: false,
        graphics_wait: None,
    };
    let bytes = b"\x1b[3~";
    let read = |gap: u64, bytes: &[u8]| Read {
        gap,
        bytes: bytes.to_vec(),
        color_queries: 0,
        wait_for_flush: false,
        semantic: false,
        nested: None,
    };
    let case = Case {
        config,
        reads: vec![read(0, &bytes[..3]), read(1, &bytes[3..])],
        expected: cut_token_rule(Kind::Key, bytes, &[Cut { at: 3, gap: 1 }], &config, 0),
        paste_end: vec![None; bytes.len()],
        kinds: vec![Kind::Key; bytes.len()],
        input: bytes.to_vec(),
        token_starts: vec![0],
    };
    // A harness seed whose first push is followed by a timeout flush.
    let seed = (0..).find(|seed| Rng(*seed).chance(1, 4)).unwrap();
    let mut harness = Harness::new(&case, seed);
    harness.run_windows_pump().unwrap();
    let expected = harness.resolve();
    assert_eq!(harness.out, vec![bytes.to_vec()]);
    assert!(check_output(&expected, &harness.out).is_ok());
    assert!(
        check_output(&expected, &[]).is_err(),
        "the loss before the quiet window passes: {expected:?}"
    );
}
